<?php
// Generates crates/vm/src/builtins/param_names.rs: the parameter names of the
// PHP functions grd implements, read by reflection from the PHP binary in the
// container (derived data). TypeErrors of builtins then name the parameter
// like PHP: "strlen(): Argument #1 ($string) must be of type string, A given".
//   php tools/gen_builtin_params.php > crates/vm/src/builtins/param_names.rs
$names = [];
foreach (glob(__DIR__ . '/../crates/vm/src/builtins/*.rs') as $f) {
    preg_match_all('/register_native\("([a-z0-9_]+)"/', file_get_contents($f), $m);
    $names = array_merge($names, $m[1]);
}
$names = array_unique($names);
sort($names, SORT_STRING);
echo "//! Parameter names of the PHP builtins grd implements, generated by\n";
echo "//! `tools/gen_builtin_params.php` from PHP " . PHP_VERSION . " (reflection). Do not edit.\n\n";
echo "pub(crate) static PARAMS: &[(&str, &[&str])] = &[\n";
foreach ($names as $n) {
    if (!function_exists($n)) { continue; }
    $params = array_map(fn ($p) => '"' . $p->getName() . '"', (new ReflectionFunction($n))->getParameters());
    echo "    (\"$n\", &[" . implode(', ', $params) . "]),\n";
}
echo "];\n";
