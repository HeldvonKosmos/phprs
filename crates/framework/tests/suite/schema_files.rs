//! R4b: the declarative schema of a project (framework fragment, main.surql,
//! blueprint.surql, manually.surql) merges in the fixed order, and SurrealDB
//! accepts the generated `temporary.surql`.

use std::path::Path;

use opengrid_framework::native::database::schema::build_surql;

fn write(root: &Path, rel: &str, text: &str) {
    let p = root.join(rel);
    std::fs::create_dir_all(p.parent().unwrap()).unwrap();
    std::fs::write(p, text).unwrap();
}

#[test]
fn project_schema_merges_and_applies() {
    let root = std::env::temp_dir().join(format!("og-schema-project-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    write(&root, "database/sources/main.surql", "DEFINE TABLE settings SCHEMALESS PERMISSIONS NONE;\n");
    write(
        &root,
        "modules/tasks/database/schema/blueprint.surql",
        "-- generated by the blueprint\nDEFINE TABLE tasks SCHEMAFULL PERMISSIONS NONE;\nDEFINE FIELD title ON tasks TYPE string;\nDEFINE FIELD note ON tasks TYPE option<string>;\nDEFINE INDEX tasks_title ON tasks FIELDS title UNIQUE;\n",
    );
    write(&root, "modules/billing/database/schema/blueprint.surql", "DEFINE FIELD amount ON invoices TYPE decimal;\nDEFINE FIELD task ON invoices TYPE record<tasks>;\n");
    // a hand edit from Surrealist: wins over the blueprint of another module too
    write(
        &root,
        "modules/billing/database/schema/manually.surql",
        "DEFINE FIELD note ON tasks TYPE option<string> DEFAULT 'none;yet';\nDEFINE ANALYZER simple TOKENIZERS blank;\n",
    );
    let fw = "DEFINE TABLE _opengrid_sessions SCHEMALESS PERMISSIONS NONE;\nDEFINE FIELD expires_at ON _opengrid_sessions TYPE datetime;\n";
    let (text, warnings) = build_surql(&root, Some(fw)).expect("build");

    assert_eq!(warnings.len(), 1, "{warnings:?}");
    assert_eq!(warnings[0].source, "modules/billing/database/schema/manually.surql");
    assert!(warnings[0].message.contains("ANALYZER"));
    let tables: Vec<&str> = text.lines().filter_map(|l| l.strip_prefix("-- TABLE: ")).collect();
    assert_eq!(tables, vec!["_opengrid_sessions", "invoices", "settings", "tasks"], "ksort: `_` (0x5F) sorts before lowercase");
    assert!(text.contains("DEFINE TABLE invoices TYPE NORMAL SCHEMAFULL PERMISSIONS NONE;"), "placeholder for a table known only from fields");
    assert!(text.contains("DEFINE FIELD note ON tasks TYPE option<string> DEFAULT 'none;yet';"), "manually wins");
    // R4h: a later file with only a field of `tasks` keeps its DEFINE TABLE
    assert!(text.contains("DEFINE TABLE tasks SCHEMAFULL PERMISSIONS NONE;"), "the blueprint's definition stays");
    assert!(!text.contains("generated by the blueprint"), "comments are not copied");

    // SurrealDB accepts the generated file as it is
    let rt = tokio::runtime::Builder::new_current_thread().enable_all().build().unwrap();
    rt.block_on(async {
        let db = surrealdb::engine::any::connect("mem://").await.expect("mem");
        db.use_ns("t").use_db("schema").await.unwrap();
        db.query(text.as_str()).await.expect("send").check().expect("all statements succeed");
        let mut r = db.query("INFO FOR TABLE tasks").await.unwrap();
        let info: Option<surrealdb::types::Value> = r.take(0).unwrap();
        let info = format!("{info:?}");
        assert!(info.contains("tasks_title") && info.contains("none;yet"), "{info}");
    });
    std::fs::remove_dir_all(&root).unwrap();
}
